NORMAL_PROMPT = """普通生成 Prompt：直接根据用户输入给一版建筑设计建议，语言自然，尽量推进方案。"""

IDENTITY_CHAIN_PROMPT = """高风险经验跳跃检查 Prompt：
本轮只检查三类高风险经验跳跃，不检查所有设计判断：
1. 道路/街道/城市支路 -> 主入口、主要人流、车行入口、接送入口。
2. 绿地/公园/庭院/景观边界 -> 安静面、景观资源、采光资源、适合安静功能。
3. 幼儿/儿童/照看/安全 -> 必须/不应该的空间规则。

如果出现上述跳跃，必须保留中间条件，写成“如果……成立，可以暂时把……作为候选方向，后续需要验证……”。
不要把回答改成五栏报告，不要检查所有判断，不要增加长篇免责声明，仍然要给一版可修改、可放弃的空间组织建议。
"""


def render_case(case: dict) -> str:
    return dedent(f"""\
        ## 案例 {case["id"]}：{case["title"]}

        **同一输入：**

        {case["input"]}

        ### A：普通生成 Prompt

        ```text
        {NORMAL_PROMPT}
        ```

        **本地样例输出：**

        {case["normal_output"].strip()}

        **身份漂移观察：**
        普通输出更容易把中间条件隐藏起来，把经验推理直接写成空间判断。

        ### B：高风险经验跳跃检查 Prompt

        ```text
        {IDENTITY_CHAIN_PROMPT.strip()}
        ```

        **本地样例输出：**

        {case["identity_output"].strip()}

        **E2 观察：**
        B 组只对道路、绿地、幼儿行为三类高风险跳跃保留中间条件；它仍然推进设计，不把整段回答改成机械五栏报告。
    """)


def build_report() -> str:
    parts = [
        "# E2 高风险经验跳跃 A/B 本地 Prompt 实验",
        "",
        "说明：本实验不调用外部 DeepSeek，不调用网络 API，不修改生产代码。",
        "A/B 输出是本地确定性样例，用于比较“只检查三类高风险经验跳跃”的实验变量；不是 live model 结果，不跑 live model。",
        "",
        "目标：比较普通生成 Prompt 与高风险经验跳跃检查 Prompt 在同一输入下，是否减少道路、绿地、幼儿行为三类跳跃的确定化。",
        "",
    ]
    for case in CASES:
        parts.append(render_case(case))
        parts.append("---")
        parts.append("")
    parts.extend([
        "## 初步读数",
        "",
        "- 普通生成 Prompt 倾向于隐藏中间推理链：道路直接变入口、绿地直接变安静/景观资源、照看需求直接变空间规则。",
        "- E2 Prompt 不检查所有设计判断，只对三类高风险经验跳跃加条件化护栏。",
        "- 观察路线：E2 本地 A/B Prompt 实验 -> 看三类跳跃是否下降 -> 如果有效 -> 再做 DeepSeek live -> 最后考虑生产 Prompt。",
        "",
        "## 验收标准",
        "",
        "1. 高风险跳跃减少：B 组不得把道路、绿地、幼儿行为直接写成确定结论。",
        "2. 设计劳动保留：B 组仍需给空间组织起点，不能退化成“信息不足无法判断”。",
        "3. 不扩大检查范围：B 组不逐条标注所有设计判断的身份。",
        "4. 不机械五栏化：用户看到的回答仍是自然导师语言。",
        "5. 不免责声明膨胀：允许关键处写待验证，但不能每句都可能/取决于。",
    ])
    return "\n".join(parts)


def write_report(path: Path = OUT) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(build_report(), encoding="utf-8")
    return path


def main() -> None:
    path = write_report()
    print(f"done -> {path}")


if __name__ == "__main__":
    main()
